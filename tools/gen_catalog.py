"""Generate editor/catalog.js from KitchenLib's GDOReferences.cs (MIT, KitchenMods/KitchenLib).

Usage: python3 tools/gen_catalog.py path/to/KitchenLib/src/References/GDOReferences.cs
The in-game "Write catalog.json" button produces an authoritative list for the installed game
(including modded appliances); the editor can import that file instead.
"""
import json, re, sys

src = open(sys.argv[1], encoding="utf-8-sig").read()
block = re.search(r"enum _ApplianceReferences\s*\{(.*?)\n\t\}", src, re.S).group(1)
entries = []
for name, value in re.findall(r"^\s*(\w+)\s*=\s*(-?\d+)", block, re.M):
    pretty = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", " ", name)
    entries.append({"id": int(value), "code": name, "name": pretty})
entries.sort(key=lambda e: e["name"].lower())
with open("editor/catalog.js", "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_catalog.py from KitchenLib GDOReferences (MIT License, KitchenMods).\n")
    f.write("// Appliance IDs are PlateUp GameDataObject IDs. Import catalog.json from the mod for an exact list.\n")
    f.write("globalThis.PLATEUP_APPLIANCES = ")
    json.dump(entries, f, separators=(",", ":"))
    f.write(";\n")
print(len(entries), "appliances")
